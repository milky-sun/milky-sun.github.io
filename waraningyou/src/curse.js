const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
const randInt = (a, b) => a + Math.floor(Math.random() * (b - a + 1));

/** 押した時間から格を求める */
export function rankFromHold(ms) {
  let rank = 1;
  for (const s of CHARGE_STEPS) if (ms >= s.ms) rank = s.rank;
  return rank;
}

/** 次の段までの案内文 */
export function chargeLabel(ms) {
  let label = CHARGE_STEPS[0].label;
  for (const s of CHARGE_STEPS) if (ms >= s.ms) label = s.label;
  return ms >= CHARGE_FULL_MS ? '　放　て　' : label;
}

/**
 * 刺さっている針から、種類の重みを決める。
 * 針が一本もなければ三種等確率。
 */
function weights(partHits) {
  const w = { work: 1, love: 1, injury: 1 };
  for (const [part, cat] of Object.entries(PART_CATEGORY)) {
    w[cat] += (partHits?.[part] || 0) * 0.6;
  }
  return w;
}

function pickCategory(partHits) {
  const w = weights(partHits);
  const total = w.work + w.love + w.injury;
  let r = Math.random() * total;
  for (const k of ['work', 'love', 'injury']) {
    r -= w[k];
    if (r <= 0) return k;
  }
  return 'injury';
}

/**
 * 呪詛をひとつ引く。
 * @param {number} holdMs 押していた時間
 * @param {object} partHits 部位ごとの命中数
 * @returns {{rank:number, category:string, categoryName:string, rankName:string,
 *            lead:string, text:string, drainDays:number}}
 */
export function drawCurse(holdMs, partHits) {
  const rank = rankFromHold(holdMs);
  const category = pickCategory(partHits);

  let text = pick(TABLE[category][rank]);

  // 大凶は追い討ちを一つ足す（本編とは別の種類から）
  if (rank === 3) {
    const others = ['work', 'love', 'injury'].filter((c) => c !== category);
    const tail = pick(TABLE[pick(others)][1]);
    text += `\n\nそのうえ ——\n${tail}`;
  }

  const [lo, hi] = DRAIN_RANGE[rank];

  return {
    rank,
    category,
    categoryName: CATEGORY_NAME[category],
    rankName: RANK_NAME[rank],
    lead: RANK_LEAD[rank],
    text,
    drainDays: randInt(lo, hi),
  };
}

