/** 殴る一発。連打が続くほど少しだけ伸びる。 */
export function punchDrain(combo) {
  const bonus = Math.min(60, combo * 1.6);
  return randInt(28, 92) + bonus;
}

/** 針一本。刺さった深さ（押した時間 0〜1）で伸びる。 */
export function needleDrain(depth) {
  return Math.round(160 + depth * 420 + Math.random() * 90);
}

/** 酸。1フレームぶん（動かした距離に比例） */
export function acidDrain(distancePx) {
  return distancePx * 1.15;
}
